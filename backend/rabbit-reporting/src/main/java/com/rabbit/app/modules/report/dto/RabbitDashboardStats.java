package com.rabbit.app.modules.report.dto;

public class RabbitDashboardStats {
    private Integer totalRabbits;
    private Integer seedRabbits;
    private Integer maleRabbits;
    private Integer femaleRabbits;
    private Integer femaleSeedRabbits;
    private Integer commodityRabbits;
    private Integer replacementRabbits;

    public Integer getTotalRabbits() {
        return totalRabbits;
    }

    public void setTotalRabbits(Integer totalRabbits) {
        this.totalRabbits = totalRabbits;
    }

    public Integer getSeedRabbits() {
        return seedRabbits;
    }

    public void setSeedRabbits(Integer seedRabbits) {
        this.seedRabbits = seedRabbits;
    }

    public Integer getMaleRabbits() {
        return maleRabbits;
    }

    public void setMaleRabbits(Integer maleRabbits) {
        this.maleRabbits = maleRabbits;
    }

    public Integer getFemaleRabbits() {
        return femaleRabbits;
    }

    public void setFemaleRabbits(Integer femaleRabbits) {
        this.femaleRabbits = femaleRabbits;
    }

    public Integer getFemaleSeedRabbits() {
        return femaleSeedRabbits;
    }

    public void setFemaleSeedRabbits(Integer femaleSeedRabbits) {
        this.femaleSeedRabbits = femaleSeedRabbits;
    }

    public Integer getCommodityRabbits() {
        return commodityRabbits;
    }

    public void setCommodityRabbits(Integer commodityRabbits) {
        this.commodityRabbits = commodityRabbits;
    }

    public Integer getReplacementRabbits() {
        return replacementRabbits;
    }

    public void setReplacementRabbits(Integer replacementRabbits) {
        this.replacementRabbits = replacementRabbits;
    }
}
